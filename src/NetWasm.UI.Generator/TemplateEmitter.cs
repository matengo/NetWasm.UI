using System.Collections.Generic;
using System.Globalization;
using System.Text;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace NetWasm.UI.Generator;

/// <summary>Turns a parsed template into a C# partial class built on <c>NetWasm.UI.Html</c>.</summary>
internal sealed class TemplateEmitter
{
    private const string H = "global::NetWasm.UI.Html.";
    private const string R = "global::NetWasm.UI.TemplateRuntime.";

    private static readonly HashSet<string> BooleanAttributes = new(System.StringComparer.OrdinalIgnoreCase)
    {
        "disabled", "checked", "hidden", "readonly", "required", "selected", "multiple", "autofocus", "open",
        "inert", "novalidate", "formnovalidate", "default", "playsinline", "nomodule",
    };

    private static readonly HashSet<string> VoidTags = new(System.StringComparer.OrdinalIgnoreCase)
    {
        "area", "base", "br", "col", "embed", "hr", "img", "input", "link", "meta", "source", "track", "wbr",
    };

    // Elements whose content the HTML parser doesn't treat as markup; their children are added in code.
    private static readonly HashSet<string> OpaqueTags = new(System.StringComparer.OrdinalIgnoreCase)
    {
        "script", "style", "textarea", "title", "template",
    };

    private readonly LineMap lines;
    private readonly string path;
    private readonly ISet<string> reactiveProps;
    private readonly IReadOnlyDictionary<string, string[]>? injectedConstructors;
    private readonly IReadOnlyDictionary<string, string[]>? genericComponents;
    private readonly StringBuilder sb = new();
    private readonly List<(string Type, string Name)> refs = new();
    private readonly List<string> templates = new();
    // Per template: its ".Listen(...)" calls (rows of an @foreach), or "" for a plain template.
    private readonly List<string> templateListeners = new();
    // Per template: whether its markup is SVG content (it is cloned inside an <svg>; see Template.Svg).
    private readonly List<bool> templateSvg = new();

    // Whether the template being emitted is cloned inside an <svg> element (and not inside a <foreignObject>).
    private bool svgContext;

    // The events a template can listen for: the ones dom.mjs delegates (Template.CanListen has the same list;
    // a test compares the three).
    internal static readonly HashSet<string> DelegatedEvents = new(System.StringComparer.Ordinal)
    {
        "click", "dblclick", "contextmenu", "input", "change", "beforeinput", "submit",
        "keydown", "keyup", "mousedown", "mouseup", "pointerdown", "pointerup", "focusin", "focusout",
    };

    /// <summary>What an @foreach row's template turns into besides its markup; see <see cref="EmitRows"/>.</summary>
    private sealed class RowParts
    {
        public readonly List<System.Action> Bind = new();
        public readonly List<System.Action> Events = new();
        public readonly StringBuilder Listeners = new();
        public int Slots;
    }
    private bool noSep;
    private bool lineHidden;

    private TemplateEmitter(string text, string path, ISet<string> reactiveProps, IReadOnlyDictionary<string, string[]>? injectedConstructors, IReadOnlyDictionary<string, string[]>? genericComponents)
    {
        this.genericComponents = genericComponents;
        lines = new LineMap(text);
        this.path = path.Replace("\"", string.Empty);
        this.reactiveProps = reactiveProps;
        this.injectedConstructors = injectedConstructors;
    }

    /// <param name="reactiveProps"><c>Component.Prop</c> names whose type is <c>Prop&lt;T&gt;</c>; the parent passes those as getters.</param>
    /// <param name="injectedConstructors">Component simple name to constructor parameter types; a tag fills them with <c>Inject&lt;T&gt;()</c>.</param>
    /// <param name="genericComponents">Generic component simple name to its type parameter names; a tag gives them as <c>TItem="Type"</c>.</param>
    public static string Emit(TemplateFile file, string text, string path, string? ns, string className, ISet<string>? reactiveProps = null, IReadOnlyDictionary<string, string[]>? injectedConstructors = null, IReadOnlyDictionary<string, string[]>? genericComponents = null)
    {
        var e = new TemplateEmitter(text, path, reactiveProps ?? new HashSet<string>(), injectedConstructors, genericComponents);
        return e.EmitFile(file, ns, className);
    }

    private string EmitFile(TemplateFile file, string? ns, string className)
    {
        var root = SingleRoot(file.Nodes, "A template", 0);
        if (root is null)
        {
            throw new TemplateException("NWUI002", "A template must contain exactly one root element.", 0, 1);
        }

        // Build the body first so @ref fields are known.
        var header = new StringBuilder();
        header.Append("// <auto-generated/>\n#nullable enable\n#pragma warning disable CS1591\n");
        header.Append("using System.Collections.Generic;\nusing System.Threading.Tasks;\nusing NetWasm.UI;\nusing NetWasm.UI.Forms;\nusing NetWasm.UI.Reactive;\nusing NetWasm.UI.Routing;\nusing static NetWasm.UI.Html;\n");

        var bodyStart = sb.Length;
        sb.Append("    protected override global::NetWasm.UI.Node Build()\n    {\n");
        foreach (var inj in file.Injects)
        {
            sb.Append("        ").Append(inj.Name.Code).Append(" = global::NetWasm.UI.Html.Inject<").Append(inj.Type.Code).Append(">();\n");
        }

        sb.Append("        OnInit();\n        return ");
        EmitNode(root, nodePosition: true);
        Hidden();
        sb.Append(";\n    }\n");
        var body = sb.ToString(bodyStart, sb.Length - bodyStart);
        sb.Length = bodyStart;

        foreach (var u in file.Usings)
        {
            User(u, "using ", ";", header);
        }

        HiddenIn(header);
        if (ns is { Length: > 0 })
        {
            header.Append("namespace ").Append(ns).Append(";\n");
        }

        header.Append("\npublic partial class ").Append(className);
        if (file.TypeParams.Count > 0)
        {
            header.Append('<');
            for (var i = 0; i < file.TypeParams.Count; i++)
            {
                header.Append(i == 0 ? string.Empty : ", ").Append(file.TypeParams[i].Name.Code);
            }

            header.Append('>');
        }

        header.Append(" : global::NetWasm.UI.Component");
        foreach (var (_, constraint) in file.TypeParams)
        {
            if (constraint is not null)
            {
                header.Append(' ').Append(constraint.Code);
            }
        }

        header.Append("\n{\n");
        foreach (var (type, name) in refs)
        {
            header.Append("    private ").Append(type).Append(' ').Append(name).Append(" = null!;\n");
        }

        for (var i = 0; i < templates.Count; i++)
        {
            header.Append("    private static readonly global::NetWasm.UI.Template __nwT").Append(i.ToString(CultureInfo.InvariantCulture));
            if (templateSvg[i])
            {
                header.Append(" = global::NetWasm.UI.Template.Svg(").Append(Literal(templates[i])).Append(')')
                    .Append(templateListeners[i]).Append(";\n");
            }
            else if (templateListeners[i].Length == 0)
            {
                header.Append(" = new(").Append(Literal(templates[i])).Append(");\n");
            }
            else
            {
                header.Append(" = new global::NetWasm.UI.Template(").Append(Literal(templates[i])).Append(')')
                    .Append(templateListeners[i]).Append(";\n");
            }
        }

        foreach (var p in file.Props)
        {
            header.Append("\n    public global::NetWasm.UI.Prop<");
            User(p.Type, string.Empty, string.Empty, header);
            HiddenIn(header);
            header.Append("    >");
            User(p.Name, string.Empty, string.Empty, header);
            HiddenIn(header);
            header.Append("    { get; set; }");
            if (p.Default is not null)
            {
                header.Append(" =");
                User(p.Default, string.Empty, string.Empty, header);
                HiddenIn(header);
            }

            header.Append(";\n");
        }

        foreach (var inj in file.Injects)
        {
            header.Append("\n    private ");
            User(inj.Type, string.Empty, string.Empty, header);
            HiddenIn(header);
            header.Append("    ");
            User(inj.Name, string.Empty, string.Empty, header);
            HiddenIn(header);
            header.Append("    = default!;\n");
        }

        header.Append("\n    /// <summary>Runs at the start of Build, inside the component's scope (Use/Provide/OnMount work here).</summary>\n");
        header.Append("    partial void OnInit();\n\n");
        header.Append(body);

        lineHidden = true;
        foreach (var block in file.CodeBlocks)
        {
            User(block, string.Empty, string.Empty, header);
        }

        header.Append("\n#line default\n");
        foreach (var block in file.CodeBlocks)
        {
            EmitReactive(block, header);
        }

        header.Append("}\n");
        return header.ToString();
    }

    /// <summary>Implements the <c>[Reactive] partial</c> properties of a <c>@code</c> block (see <see cref="ReactiveMember"/>).</summary>
    private static void EmitReactive(Directive block, StringBuilder target)
    {
        const string Prefix = "class __C {";
        var tree = CSharpSyntaxTree.ParseText(Prefix + block.Code + "\n}");
        foreach (var node in tree.GetRoot().DescendantNodes())
        {
            if (node is not PropertyDeclarationSyntax { Parent: ClassDeclarationSyntax { Identifier.ValueText: "__C" } } p
                || ReactiveMember.Find(p) is not { } attribute)
            {
                continue;
            }

            var problem = ReactiveMember.CheckShape(p);
            if (problem is not null)
            {
                throw new TemplateException(
                    "NWUI002", "[Reactive] property '" + p.Identifier.ValueText + "' " + problem, block.Start + p.Identifier.SpanStart - Prefix.Length, p.Identifier.Span.Length);
            }

            var args = attribute.ArgumentList?.Arguments;
            var initial = args is { Count: 1 } ? args.Value[0].Expression.ToString() : "default!";
            target.Append('\n').Append(ReactiveMember.Emit(p, p.Type.ToString(), initial));
        }
    }

    // ---- nodes ----

    /// <summary>Emits a node as Content (inside an element) or as a Node (root / branch body).</summary>
    private void EmitNode(TNode node, bool nodePosition)
    {
        switch (node)
        {
            case TText t:
                var literal = Literal(Decode(t.Raw, t.Start));
                sb.Append(nodePosition ? H + "Text(" + literal + ")" : literal);
                break;
            case TExpr x:
                sb.Append(H).Append("Text(() => ");
                User(x.Code);
                sb.Append(')');
                break;
            case TRender r:
                // @render(Cell, row) renders a Slot<T> with an argument; without the call it would be a tuple.
                sb.Append(CSharpScanner.ScanUntil(r.Code.Code, 0, ',') >= 0 ? R + "Render(" : "(");
                User(r.Code);
                sb.Append(')');
                break;
            case TElement el when el.IsComponent:
                EmitComponent(el, nodePosition);
                break;
            case TElement el:
                EmitElement(el);
                break;
            case TIf i:
                if (nodePosition)
                {
                    throw Structure("'@if' cannot be the only content of a template or block; wrap it in an element.", i.Start, 3);
                }

                EmitIf(i);
                break;
            case TForeach f:
                if (nodePosition)
                {
                    throw Structure("'@foreach' cannot be the only content of a template or block; wrap it in an element.", f.Start, 8);
                }

                EmitForeach(f);
                if (f.AnimateExit)
                {
                    sb.Append(".AnimateExit()");
                }

                break;
        }
    }

    /// <summary>
    /// A native element becomes a clone of a static <c>Template</c>: literal markup goes into the HTML once,
    /// and only the dynamic parts (bound attributes, handlers, <c>@expr</c> text, components, blocks) are
    /// filled in per instance through holes.
    /// </summary>
    private void EmitElement(TElement el, TAttribute? skip = null)
    {
        var html = new StringBuilder();
        var calls = new List<System.Action>();
        var holeCount = 0;
        BuildTemplate(el, skip, isRoot: true, html, calls, ref holeCount, svgContext);

        var index = TemplateIndex(html.ToString(), string.Empty);
        sb.Append("__nwT").Append(index.ToString(CultureInfo.InvariantCulture)).Append(".Clone()");
        foreach (var call in calls)
        {
            call();
        }

        sb.Append(".Root");
    }

    private int TemplateIndex(string markup, string listeners)
    {
        for (var i = 0; i < templates.Count; i++)
        {
            if (templates[i] == markup && templateListeners[i] == listeners && templateSvg[i] == svgContext)
            {
                return i;
            }
        }

        templates.Add(markup);
        templateListeners.Add(listeners);
        templateSvg.Add(svgContext);
        return templates.Count - 1;
    }

    /// <summary>
    /// The element of an <c>@foreach</c> body as rows of a template (<c>TemplateRuntime.Rows</c>). What a row
    /// needs is emitted as functions of the loop variable, shared by all rows, instead of a closure, effect and
    /// listener per row and binding: <c>@expr</c> text and plain bound attributes go into one bind function,
    /// delegated <c>@on…</c> handlers become listeners of the template plus one events function, and everything
    /// else (components, blocks, <c>@bind</c>, <c>@ref</c>, …) stays content applied once per row.
    /// </summary>
    private void EmitRows(TForeach node, TElement root, TAttribute? key)
    {
        var html = new StringBuilder();
        var calls = new List<System.Action>();
        var holeCount = 0;
        var row = new RowParts();
        BuildTemplate(root, key, isRoot: true, html, calls, ref holeCount, svgContext, row);
        var index = TemplateIndex(html.ToString(), row.Listeners.ToString());

        // With a typed loop variable every lambda parameter needs its type.
        var typed = node.Type is not null;
        var head = typed
            ? "(global::NetWasm.UI.TemplateRow __nwRow, " + node.Type + " " + node.Variable
            : "(__nwRow, " + node.Variable;

        sb.Append(R).Append("Rows(() => ");
        User(node.Collection);
        if (key is not null)
        {
            sb.Append(", ").Append(typed ? "(" + node.Type + " " + node.Variable + ")" : node.Variable).Append(" => ");
            User(key.Code ?? throw Parse("'@key' needs a value.", key.Start, 4));
        }

        sb.Append(", __nwT").Append(index.ToString(CultureInfo.InvariantCulture))
            .Append(", ").Append(row.Slots.ToString(CultureInfo.InvariantCulture)).Append(", ");
        if (calls.Count == 0)
        {
            sb.Append("null");
        }
        else
        {
            sb.Append(head).Append(") => __nwRow.Instance");
            foreach (var call in calls)
            {
                call();
            }
        }

        sb.Append(", ");
        if (row.Bind.Count == 0)
        {
            sb.Append("null");
        }
        else
        {
            sb.Append(head).Append(") => { ");
            foreach (var bind in row.Bind)
            {
                bind();
            }

            sb.Append(" }");
        }

        if (row.Events.Count > 0)
        {
            sb.Append(", ").Append(head)
                .Append(typed ? ", int __nwSlot, global::NetWasm.UI.DomEvent __nwEvent) => { switch (__nwSlot) { " : ", __nwSlot, __nwEvent) => { switch (__nwSlot) { ");
            foreach (var handler in row.Events)
            {
                handler();
            }

            sb.Append(" } }");
        }

        sb.Append(')');
    }

    // In a row, a bound attribute that is plain text (not value, not a boolean attribute) is written by the
    // row's bind function.
    private static bool IsRowAttribute(TAttribute a)
    {
        if (a.IsDirective || !a.HasValue || a.Name == "value" || (a.Segments.Count == 1 && BooleanAttributes.Contains(a.Name)))
        {
            return false;
        }

        foreach (var seg in a.Segments)
        {
            if (seg.IsCode)
            {
                return true;
            }
        }

        return false;
    }

    /// <param name="svg">Whether <paramref name="el"/> sits in SVG content: inside an <c>&lt;svg&gt;</c> and not inside a
    /// <c>&lt;foreignObject&gt;</c>. Blocks and components inside it are emitted in the same context, so their
    /// templates are SVG content too (<c>Template.Svg</c>).</param>
    private void BuildTemplate(TElement el, TAttribute? skip, bool isRoot, StringBuilder html, List<System.Action> calls, ref int holeCount, bool svg, RowParts? row = null)
    {
        var childSvg = (svg || string.Equals(el.Tag, "svg", System.StringComparison.OrdinalIgnoreCase))
            && !string.Equals(el.Tag, "foreignObject", System.StringComparison.OrdinalIgnoreCase);
        var refName = RefOf(el, "global::NetWasm.UI.Element");
        var dynamic = new TElement(el.Tag);
        var statics = new List<TAttribute>();
        var splat = HasSplat(el, skip);
        var afterSplat = false;
        string? baseClass = null;
        string? baseStyle = null;
        foreach (var a in el.Attributes)
        {
            if (a == skip || a.Name == "@ref")
            {
                continue;
            }

            afterSplat |= a.Name == "@attributes";

            // 'value' stays a property (as before) so it also works on <select> and after user edits.
            if (a.IsDirective || a.Name == "value" || !IsLiteral(a))
            {
                dynamic.Attributes.Add(a);
            }
            else if (splat && a.Name is "class" or "style")
            {
                // Stays in the markup; the splat joins its own class/style onto it.
                statics.Add(a);
                var value = LiteralValue(a);
                if (a.Name == "class")
                {
                    baseClass = baseClass is null ? value : baseClass + " " + value;
                }
                else
                {
                    baseStyle = baseStyle is null ? value : baseStyle + ";" + value;
                }
            }
            else if (afterSplat)
            {
                // A static attribute after @attributes overrides the splat, so it is applied after it.
                dynamic.Attributes.Add(a);
            }
            else
            {
                statics.Add(a);
            }
        }

        var children = Trim(el.Children);
        var isVoid = VoidTags.Contains(el.Tag);
        var opaque = OpaqueTags.Contains(el.Tag);

        // Trailing components/blocks are appended to the element itself; earlier ones need an insertion point.
        var tail = children.Count;
        if (opaque)
        {
            tail = 0;
        }
        else
        {
            while (tail > 0 && IsInsertable(children[tail - 1]))
            {
                tail--;
            }
        }

        var needsHole = refName is not null || dynamic.Attributes.Count > 0 || tail < children.Count;
        var hole = isRoot ? 0 : needsHole ? ++holeCount : -1;

        html.Append('<').Append(el.Tag);
        if (!isRoot && needsHole)
        {
            html.Append(" $");
        }

        foreach (var a in statics)
        {
            html.Append(' ').Append(a.Name);
            if (a.HasValue)
            {
                var value = new StringBuilder();
                foreach (var seg in a.Segments)
                {
                    value.Append(Decode(seg.Text, seg.Start));
                }

                html.Append("=\"").Append(Escape(value.ToString(), attribute: true)).Append('"');
            }
        }

        html.Append('>');

        if (refName is not null)
        {
            calls.Add(() => sb.Append(".Ref(").Append(hole.ToString(CultureInfo.InvariantCulture)).Append(", out ").Append(refName).Append(')'));
        }

        if (row is not null && !splat)
        {
            // Listeners first, in source order: a handler's modifiers decide its flags wherever they stand.
            var handlers = new List<TAttribute>();
            foreach (var a in dynamic.Attributes)
            {
                if (a.IsDirective && a.Name.StartsWith("@on", System.StringComparison.Ordinal) && a.Name.Length > 3)
                {
                    handlers.Add(a);
                }
            }

            var listened = new HashSet<string>(System.StringComparer.Ordinal);
            foreach (var (evt, handler, flags) in ResolveHandlers(handlers))
            {
                // Capture (8) and passive (16) listeners are added on the element itself, not delegated.
                if (!DelegatedEvents.Contains(evt) || (flags & (8 | 16)) != 0 || row.Events.Count == 255)
                {
                    continue;
                }

                listened.Add(evt);
                var slot = row.Events.Count;
                row.Listeners.Append(".Listen(").Append(hole.ToString(CultureInfo.InvariantCulture)).Append(", ").Append(Literal(evt))
                    .Append(", (global::NetWasm.UI.Dom.ListenerFlags)").Append(flags.ToString(CultureInfo.InvariantCulture)).Append(')');
                row.Events.Add(() =>
                {
                    sb.Append("case ").Append(slot.ToString(CultureInfo.InvariantCulture)).Append(": ").Append(R).Append("Invoke(");
                    User(handler.Code!);
                    sb.Append(", __nwEvent); break; ");
                });
            }

            var rest = new TElement(el.Tag);
            foreach (var a in dynamic.Attributes)
            {
                if (IsRowAttribute(a))
                {
                    var slot = row.Slots++;
                    row.Bind.Add(() =>
                    {
                        sb.Append("__nwRow.Attr(").Append(slot.ToString(CultureInfo.InvariantCulture)).Append(", ")
                            .Append(hole.ToString(CultureInfo.InvariantCulture)).Append(", ").Append(Literal(a.Name)).Append(", ");
                        EmitInterpolated(a.Segments, "AttrStr");
                        sb.Append("); ");
                    });
                }
                else if (!(a.IsDirective && a.Name.StartsWith("@on", System.StringComparison.Ordinal) && listened.Contains(EventOf(a))))
                {
                    rest.Attributes.Add(a);
                }
            }

            dynamic = rest;
        }

        if (dynamic.Attributes.Count > 0)
        {
            calls.Add(() =>
            {
                sb.Append(".With(").Append(hole.ToString(CultureInfo.InvariantCulture));
                EmitAttributes(dynamic, null, baseClass, baseStyle);
                sb.Append(')');
            });
        }

        if (isVoid)
        {
            return;
        }

        for (var i = 0; i < tail; i++)
        {
            var child = children[i];
            switch (child)
            {
                case TText t:
                    html.Append(Escape(Decode(t.Raw, t.Start), attribute: false));
                    break;
                case TExpr x:
                {
                    html.Append("<!--$-->");
                    var h = ++holeCount;
                    if (row is not null)
                    {
                        var slot = row.Slots++;
                        row.Bind.Add(() =>
                        {
                            sb.Append("__nwRow.Text(").Append(slot.ToString(CultureInfo.InvariantCulture)).Append(", ")
                                .Append(h.ToString(CultureInfo.InvariantCulture)).Append(", ");
                            User(x.Code);
                            sb.Append("); ");
                        });
                        break;
                    }

                    calls.Add(() =>
                    {
                        sb.Append(".Text(").Append(h.ToString(CultureInfo.InvariantCulture)).Append(", () => ");
                        User(x.Code);
                        sb.Append(')');
                    });
                    break;
                }

                case TElement e when !e.IsComponent:
                    BuildTemplate(e, null, isRoot: false, html, calls, ref holeCount, childSvg, row);
                    break;
                default:
                {
                    html.Append("<!--@-->");
                    var h = ++holeCount;
                    calls.Add(() =>
                    {
                        sb.Append(".With(").Append(h.ToString(CultureInfo.InvariantCulture)).Append(", ");
                        InSvgContext(childSvg, () => EmitNode(child, nodePosition: false));
                        sb.Append(')');
                    });
                    break;
                }
            }
        }

        if (tail < children.Count)
        {
            calls.Add(() =>
            {
                sb.Append(".With(").Append(hole.ToString(CultureInfo.InvariantCulture));
                for (var i = tail; i < children.Count; i++)
                {
                    sb.Append(", ");
                    var child = children[i];
                    InSvgContext(childSvg, () => EmitNode(child, nodePosition: false));
                }

                sb.Append(')');
            });
        }

        html.Append("</").Append(el.Tag).Append('>');
    }

    private void InSvgContext(bool svg, System.Action emit)
    {
        var saved = svgContext;
        svgContext = svg;
        try
        {
            emit();
        }
        finally
        {
            svgContext = saved;
        }
    }

    private static bool IsInsertable(TNode node) =>
        node is TRender or TIf or TForeach || node is TElement { IsComponent: true };

    private string LiteralValue(TAttribute a)
    {
        var value = new StringBuilder();
        foreach (var seg in a.Segments)
        {
            value.Append(Decode(seg.Text, seg.Start));
        }

        return value.ToString();
    }

    private static bool IsLiteral(TAttribute a)
    {
        foreach (var seg in a.Segments)
        {
            if (seg.IsCode)
            {
                return false;
            }
        }

        return true;
    }

    private static string Escape(string text, bool attribute)
    {
        var b = new StringBuilder(text.Length);
        foreach (var c in text)
        {
            switch (c)
            {
                case '&': b.Append("&amp;"); break;
                case '<': b.Append(attribute ? "<" : "&lt;"); break;
                case '>': b.Append(attribute ? ">" : "&gt;"); break;
                case '"': b.Append(attribute ? "&quot;" : "\""); break;
                default: b.Append(c); break;
            }
        }

        return b.ToString();
    }

    private void EmitChildren(List<TNode> children)
    {
        foreach (var child in Trim(children))
        {
            sb.Append(", ");
            EmitNode(child, nodePosition: false);
        }
    }

    private void EmitAttributes(TElement el, TAttribute? skip, string? baseClass = null, string? baseStyle = null)
    {
        var handlers = new List<TAttribute>();
        var splat = HasSplat(el, skip);
        if (splat)
        {
            // With @attributes, the element's own attributes go through the splat so source order decides who wins.
            Sep();
            sb.Append(H).Append("Splat(new global::NetWasm.UI.Content[] { ");
            noSep = true;
        }

        foreach (var a in el.Attributes)
        {
            if (a == skip || a.Name == "@ref")
            {
                continue;
            }

            if (a.IsDirective)
            {
                if (a.Name == "@attributes")
                {
                    Sep();
                    EmitSplatExpression(a);
                }
                else if (a.Name == "@bind")
                {
                    Sep();
                    sb.Append(H).Append("Spread(").Append(H).Append("Bind(");
                    User(a.Code!);
                    sb.Append("))");
                }
                else if (a.Name.StartsWith("@on", System.StringComparison.Ordinal) && a.Name.Length > 3)
                {
                    handlers.Add(a);
                }
                else if (a.Name == "@key")
                {
                    throw Structure("'@key' is only allowed on the root element of an '@foreach' body.", a.Start, a.Name.Length);
                }
                else
                {
                    throw Unsupported($"Unknown directive attribute '{a.Name}' (supported: @attributes, @bind, @ref, @key, @on<event>[:preventDefault|:stopPropagation|:capture|:passive]).", a.Start, a.Name.Length);
                }

                continue;
            }

            Sep();
            EmitAttribute(a);
        }

        if (splat)
        {
            noSep = false;
            sb.Append(" }, ").Append(baseClass is null ? "null" : Literal(baseClass))
                .Append(", ").Append(baseStyle is null ? "null" : Literal(baseStyle)).Append(')');
        }

        EmitHandlers(handlers);
    }

    private static bool HasSplat(TElement el, TAttribute? skip)
    {
        foreach (var a in el.Attributes)
        {
            if (a != skip && a.Name == "@attributes")
            {
                return true;
            }
        }

        return false;
    }

    private void EmitSplatExpression(TAttribute a)
    {
        sb.Append(H).Append("Splat(");
        User(a.Code ?? throw Parse("'@attributes' needs a value, e.g. @attributes=\"Attributes\".", a.Start, a.Name.Length));
        sb.Append(')');
    }

    /// <summary>Starts the next item of an argument or array list (no comma before the first array item).</summary>
    private void Sep()
    {
        if (noSep)
        {
            noSep = false;
        }
        else
        {
            sb.Append(", ");
        }
    }

    /// <summary>
    /// On a component tag, a name that starts lowercase or contains '-' (<c>class</c>, <c>aria-label</c>,
    /// <c>data-x</c>) is an HTML attribute for <c>Component.Attributes</c>; PascalCase names are properties.
    /// </summary>
    private static bool IsHtmlAttribute(string name) =>
        (name.Length > 0 && name[0] >= 'a' && name[0] <= 'z') || name.IndexOf('-') >= 0;

    private void EmitAttribute(TAttribute a)
    {
        var name = a.Name;
        var isValue = name == "value";
        if (!a.HasValue)
        {
            sb.Append(H).Append("Attr(").Append(Literal(name)).Append(", \"\")");
            return;
        }

        var allLiteral = true;
        foreach (var seg in a.Segments)
        {
            allLiteral &= !seg.IsCode;
        }

        if (allLiteral)
        {
            var text = new StringBuilder();
            foreach (var seg in a.Segments)
            {
                text.Append(Decode(seg.Text, seg.Start));
            }

            sb.Append(H).Append(isValue ? "Value(" : "Attr(" + Literal(name) + ", ").Append(Literal(text.ToString())).Append(')');
            return;
        }

        if (a.Segments.Count == 1 && BooleanAttributes.Contains(name))
        {
            sb.Append(name == "checked" ? H + "Checked(() => " : "global::NetWasm.UI.Attr.Toggle(" + Literal(name) + ", () => ");
            User(a.Segments[0]);
            sb.Append(')');
            return;
        }

        sb.Append(H).Append(isValue ? "Value(() => " : "Attr(" + Literal(name) + ", () => ");
        EmitInterpolated(a.Segments, "AttrStr");
        if (isValue)
        {
            sb.Append(" ?? \"\"");
        }

        sb.Append(')');
    }

    /// <summary>Emits a <c>string?</c> expression for literal text mixed with <c>@expr</c> pieces.</summary>
    /// <param name="format"><c>Str</c>, or <c>AttrStr</c> for HTML attribute values (<c>bool</c> becomes <c>"true"</c>/<c>"false"</c>).</param>
    private void EmitInterpolated(List<Segment> segments, string format = "Str")
    {
        if (segments.Count == 1)
        {
            sb.Append(R).Append(format).Append('(');
            User(segments[0]);
            sb.Append(')');
            return;
        }

        sb.Append("string.Concat(new string?[] { ");
        for (var i = 0; i < segments.Count; i++)
        {
            if (i > 0)
            {
                sb.Append(", ");
            }

            var seg = segments[i];
            if (seg.IsCode)
            {
                sb.Append(R).Append(format).Append('(');
                User(seg);
                sb.Append(')');
            }
            else
            {
                sb.Append(Literal(Decode(seg.Text, seg.Start)));
            }
        }

        sb.Append(" })");
    }

    private static string EventOf(TAttribute a)
    {
        var spec = a.Name.Substring(3);
        var colon = spec.IndexOf(':');
        return colon < 0 ? spec : spec.Substring(0, colon);
    }

    private void EmitHandlers(List<TAttribute> attrs)
    {
        foreach (var (evt, a, flags) in ResolveHandlers(attrs))
        {
            Sep();
            sb.Append(H).Append("On(").Append(Literal(evt)).Append(", ");
            User(a.Code!);
            sb.Append(", (global::NetWasm.UI.Dom.ListenerFlags)").Append(flags.ToString(CultureInfo.InvariantCulture)).Append(')');
        }
    }

    // Each event's handler and listener flags, in the order the events first appear.
    private List<(string Event, TAttribute Handler, int Flags)> ResolveHandlers(List<TAttribute> attrs)
    {
        var events = new List<string>();
        var handler = new Dictionary<string, TAttribute>();
        var flags = new Dictionary<string, int>();
        var first = new Dictionary<string, TAttribute>();
        foreach (var a in attrs)
        {
            var spec = a.Name.Substring(3);
            var colon = spec.IndexOf(':');
            var evt = colon < 0 ? spec : spec.Substring(0, colon);
            if (evt.Length == 0)
            {
                throw Parse($"Missing event name in '{a.Name}'.", a.Start, a.Name.Length);
            }

            if (!first.ContainsKey(evt))
            {
                first[evt] = a;
                events.Add(evt);
                flags[evt] = evt == "submit" ? 1 : 0;
            }

            if (colon < 0)
            {
                if (a.Code is null)
                {
                    throw Parse($"'{a.Name}' needs a handler, e.g. {a.Name}=\"() => ...\".", a.Start, a.Name.Length);
                }

                if (handler.ContainsKey(evt))
                {
                    throw Structure($"Duplicate handler for '{evt}'.", a.Start, a.Name.Length);
                }

                handler[evt] = a;
                continue;
            }

            var modifier = spec.Substring(colon + 1);
            int bit;
            if (modifier == "preventDefault")
            {
                bit = 1;
            }
            else if (modifier == "stopPropagation")
            {
                bit = 2;
            }
            else if (modifier == "capture")
            {
                bit = 8;
            }
            else if (modifier == "passive")
            {
                bit = 16;
            }
            else
            {
                throw Unsupported($"Unknown event modifier ':{modifier}' (supported: :preventDefault, :stopPropagation, :capture, :passive).", a.Start, a.Name.Length);
            }

            var on = true;
            if (a.Code is not null)
            {
                var v = a.Code.Code.Trim();
                if (v != "true" && v != "false")
                {
                    throw Unsupported($"'{a.Name}' must be \"true\" or \"false\".", a.Start, a.Name.Length);
                }

                on = v == "true";
            }

            flags[evt] = on ? flags[evt] | bit : flags[evt] & ~bit;
        }

        var resolved = new List<(string Event, TAttribute Handler, int Flags)>();
        foreach (var evt in events)
        {
            if (!handler.TryGetValue(evt, out var a))
            {
                var f = first[evt];
                throw Structure($"Modifier '{f.Name}' without an '@on{evt}' handler.", f.Start, f.Name.Length);
            }

            if ((flags[evt] & 16) != 0 && (flags[evt] & 1) != 0)
            {
                var f = first[evt];
                throw Structure($"'@on{evt}' cannot be both :passive and :preventDefault.", f.Start, f.Name.Length);
            }

            resolved.Add((evt, a, flags[evt]));
        }

        return resolved;
    }

    private void EmitComponent(TElement el, bool nodePosition, TAttribute? skip = null)
    {
        if (el.Tag is "Link" or "NavLink")
        {
            EmitLink(el, skip);
            return;
        }

        if (el.Tag == "ErrorBoundary")
        {
            if (nodePosition)
            {
                throw Structure("<ErrorBoundary> cannot be the only content of a template or block; wrap it in an element.", el.Start, el.Tag.Length + 1);
            }

            EmitErrorBoundary(el);
            return;
        }

        if (el.Tag == "Suspense")
        {
            if (nodePosition)
            {
                throw Structure("<Suspense> cannot be the only content of a template or block; wrap it in an element.", el.Start, el.Tag.Length + 1);
            }

            EmitSuspense(el);
            return;
        }

        var slots = SlotsOf(el);
        var typeArgAttrs = new List<TAttribute>();
        var typeArgs = TypeArgumentsOf(el, typeArgAttrs);
        var refName = RefOf(el, el.Tag + typeArgs);
        if (refName is not null)
        {
            sb.Append('(').Append(refName).Append(" = ");
        }

        sb.Append("new ").Append(el.Tag).Append(typeArgs);
        var dot = el.Tag.LastIndexOf('.');
        if (injectedConstructors is not null && injectedConstructors.TryGetValue(dot < 0 ? el.Tag : el.Tag.Substring(dot + 1), out var parameters))
        {
            sb.Append('(');
            for (var i = 0; i < parameters.Length; i++)
            {
                sb.Append(i == 0 ? string.Empty : ", ").Append("global::NetWasm.UI.Html.Inject<").Append(parameters[i]).Append(">()");
            }

            sb.Append(')');
        }

        sb.Append(" {");
        var any = false;
        var html = new List<TAttribute>();
        foreach (var a in el.Attributes)
        {
            if (a == skip || a.Name == "@ref" || typeArgAttrs.Contains(a))
            {
                continue;
            }

            if (a.Name.StartsWith("@bind-", System.StringComparison.Ordinal))
            {
                // @bind-Value="signal" hands the component the signal itself, so it can read and write it.
                var prop = a.Name.Substring(6);
                if (prop.Length == 0 || !CSharpScanner.IsIdentStart(prop[0]) || CSharpScanner.ScanIdent(prop, 0) != prop.Length || a.Code is null)
                {
                    throw Parse("'@bind-' on a component needs a property name and a value, e.g. @bind-Value=\"name\".", a.Start, a.Name.Length);
                }

                sb.Append(any ? "," : string.Empty);
                any = true;
                User(new Directive(prop, a.Start + 6));
                sb.Append(" = ");
                User(a.Code);
                continue;
            }

            if (a.IsDirective)
            {
                if (a.Name != "@attributes" && !(a.Name.StartsWith("@on", System.StringComparison.Ordinal) && a.Name.Length > 3))
                {
                    throw Unsupported($"'{a.Name}' is not supported on components (supported: @attributes, @bind-<Prop>, @ref, @on<event>).", a.Start, a.Name.Length);
                }

                html.Add(a);
                continue;
            }

            if (IsHtmlAttribute(a.Name))
            {
                html.Add(a);
                continue;
            }

            sb.Append(any ? "," : string.Empty);
            any = true;
            User(new Directive(a.Name, a.Start));
            sb.Append(" = ");
            if (IsReactiveProp(el.Tag, a.Name))
            {
                EmitReactivePropValue(a);
            }
            else
            {
                EmitPropValue(a);
            }
        }

        if (html.Count > 0)
        {
            sb.Append(any ? "," : string.Empty);
            any = true;
            sb.Append(" Attributes = new global::NetWasm.UI.Content[] { ");
            noSep = true;
            var handlers = new List<TAttribute>();
            foreach (var a in html)
            {
                if (a.Name == "@attributes")
                {
                    Sep();
                    EmitSplatExpression(a);
                }
                else if (a.IsDirective)
                {
                    handlers.Add(a);
                }
                else
                {
                    Sep();
                    EmitAttribute(a);
                }
            }

            EmitHandlers(handlers);
            noSep = false;
            sb.Append(" }");
        }

        foreach (var (name, start, context, body) in slots)
        {
            sb.Append(any ? "," : string.Empty);
            any = true;
            User(new Directive(name, start));
            if (context is null)
            {
                sb.Append(" = new global::NetWasm.UI.Slot(() => new global::NetWasm.UI.Content[] {");
            }
            else
            {
                // Target-typed: the property's Slot<T> gives the lambda parameter its type.
                sb.Append(" = new(");
                User(context);
                sb.Append(" => new global::NetWasm.UI.Content[] {");
            }

            for (var i = 0; i < body.Count; i++)
            {
                sb.Append(i == 0 ? " " : ", ");
                EmitNode(body[i], nodePosition: false);
            }

            sb.Append(" })");
        }

        sb.Append(any ? " }" : "}");
        if (refName is not null)
        {
            sb.Append(')');
        }

        if (nodePosition)
        {
            sb.Append(".Render()");
        }
    }

    /// <summary>
    /// <c>&lt;Name&lt;Type&gt;&gt;</c> for a generic component: its type parameters come from attributes with their names
    /// (<c>&lt;DataTable TItem="Person"&gt;</c>), which are added to <paramref name="used"/>. Empty for other components.
    /// </summary>
    private string TypeArgumentsOf(TElement el, List<TAttribute> used)
    {
        var dot = el.Tag.LastIndexOf('.');
        if (genericComponents is null || !genericComponents.TryGetValue(dot < 0 ? el.Tag : el.Tag.Substring(dot + 1), out var names))
        {
            return string.Empty;
        }

        var result = new StringBuilder("<");
        for (var i = 0; i < names.Length; i++)
        {
            TAttribute? found = null;
            foreach (var a in el.Attributes)
            {
                if (a.Name == names[i])
                {
                    found = a;
                }
            }

            if (found is null)
            {
                var all = string.Join(", ", System.Array.ConvertAll(names, n => n + "=\"…\""));
                throw Structure($"<{el.Tag}> is generic; give its type arguments: {all}.", el.Start, el.Tag.Length + 1);
            }

            if (!found.HasValue || found.Segments.Count != 1 || found.Segments[0].IsCode || found.Segments[0].Text.Trim().Length == 0)
            {
                throw Parse($"'{names[i]}' must name a type, e.g. {names[i]}=\"Person\".", found.Start, found.Name.Length);
            }

            used.Add(found);
            result.Append(i == 0 ? string.Empty : ", ").Append(found.Segments[0].Text.Trim());
        }

        return result.Append('>').ToString();
    }

    /// <summary>
    /// A component's child content: <c>&lt;template slot="Name"&gt;…&lt;/template&gt;</c> children fill the
    /// <c>Name</c> slot; everything else goes to <c>ChildContent</c>. With <c>context="row"</c> the slot is a
    /// <c>Slot&lt;T&gt;</c> and its body can use <c>row</c>.
    /// </summary>
    private static List<(string Name, int Start, Directive? Context, List<TNode> Body)> SlotsOf(TElement el)
    {
        var slots = new List<(string Name, int Start, Directive? Context, List<TNode> Body)>();
        var loose = new List<TNode>();
        foreach (var child in Trim(el.Children))
        {
            if (child is not TElement { Tag: "template" } t)
            {
                loose.Add(child);
                continue;
            }

            TAttribute? slot = null;
            Directive? context = null;
            foreach (var a in t.Attributes)
            {
                if (a.Name == "context")
                {
                    var ctx = a.HasValue && a.Segments.Count == 1 && !a.Segments[0].IsCode ? a.Segments[0].Text.Trim() : string.Empty;
                    if (ctx.Length == 0 || !CSharpScanner.IsIdentStart(ctx[0]) || CSharpScanner.ScanIdent(ctx, 0) != ctx.Length)
                    {
                        throw Parse("'context' must name the slot's argument, e.g. context=\"row\".", a.Start, a.Name.Length);
                    }

                    context = new Directive(ctx, a.Segments[0].Start);
                    continue;
                }

                if (a.Name != "slot")
                {
                    throw Unsupported($"'{a.Name}' is not supported on a slot <template>; only 'slot' and 'context' are.", a.Start, a.Name.Length);
                }

                slot = a;
            }

            if (slot is null || !slot.HasValue || slot.Segments.Count != 1 || slot.Segments[0].IsCode)
            {
                throw Structure("A <template> inside a component needs slot=\"Name\".", t.Start, t.Tag.Length + 1);
            }

            var name = slot.Segments[0].Text.Trim();
            if (name.Length == 0 || !CSharpScanner.IsIdentStart(name[0]) || CSharpScanner.ScanIdent(name, 0) != name.Length)
            {
                throw Parse($"'{name}' is not a valid slot name; use a property name like slot=\"Header\".", slot.Segments[0].Start, System.Math.Max(1, slot.Segments[0].Text.Length));
            }

            Add(name, slot.Segments[0].Start, context, Trim(t.Children));
        }

        if (loose.Count > 0)
        {
            Add("ChildContent", loose[0].Start, null, loose);
        }

        return slots;

        void Add(string name, int start, Directive? context, List<TNode> body)
        {
            foreach (var s in slots)
            {
                if (s.Name == name)
                {
                    var hint = name == "ChildContent" ? " (loose child content fills 'ChildContent')" : string.Empty;
                    throw Structure($"Slot '{name}' is given more than once{hint}.", start, 1);
                }
            }

            slots.Add((name, start, context, body));
        }
    }

    private bool IsReactiveProp(string tag, string prop)
    {
        var dot = tag.LastIndexOf('.');
        return reactiveProps.Contains((dot < 0 ? tag : tag.Substring(dot + 1)) + "." + prop);
    }

    /// <summary>
    /// For a <c>Prop&lt;T&gt;</c> prop, <c>Prop="@expr"</c> becomes <c>new(() => expr)</c> so the child re-reads it
    /// (and tracks what it reads). Literals and bare props still convert implicitly from the value.
    /// </summary>
    private void EmitReactivePropValue(TAttribute a)
    {
        var hasCode = false;
        foreach (var seg in a.Segments)
        {
            hasCode |= seg.IsCode;
        }

        if (!a.HasValue || !hasCode)
        {
            EmitPropValue(a);
            return;
        }

        sb.Append("new(() => ");
        EmitPropValue(a);
        sb.Append(')');
    }

    /// <summary>Literal props are strings; <c>Prop="@expr"</c> passes the expression as-is; a bare <c>Prop</c> is <c>true</c>.</summary>
    private void EmitPropValue(TAttribute a)
    {
        if (!a.HasValue)
        {
            sb.Append("true");
            return;
        }

        if (a.Segments.Count == 1 && a.Segments[0].IsCode)
        {
            User(a.Segments[0]);
            return;
        }

        var allLiteral = true;
        foreach (var seg in a.Segments)
        {
            allLiteral &= !seg.IsCode;
        }

        if (allLiteral)
        {
            var text = new StringBuilder();
            foreach (var seg in a.Segments)
            {
                text.Append(Decode(seg.Text, seg.Start));
            }

            sb.Append(Literal(text.ToString()));
            return;
        }

        sb.Append('(');
        EmitInterpolated(a.Segments);
        sb.Append(" ?? \"\")");
    }

    /// <summary>
    /// <c>&lt;ErrorBoundary&gt;content&lt;template slot="Fallback" context="error"&gt;…&lt;/template&gt;&lt;/ErrorBoundary&gt;</c>
    /// becomes <c>Html.ErrorBoundary(() =&gt; content, (BoundaryError error) =&gt; fallback)</c>.
    /// </summary>
    private void EmitErrorBoundary(TElement el)
    {
        if (el.Attributes.Count > 0)
        {
            var a = el.Attributes[0];
            throw Unsupported($"'{a.Name}' is not supported on <ErrorBoundary>.", a.Start, a.Name.Length);
        }

        TElement? fallback = null;
        var context = "error";
        var content = new List<TNode>();
        foreach (var child in Trim(el.Children))
        {
            if (child is not TElement { Tag: "template" } t)
            {
                content.Add(child);
                continue;
            }

            TAttribute? slot = null;
            foreach (var a in t.Attributes)
            {
                if (a.Name == "slot")
                {
                    slot = a;
                }
                else if (a.Name == "context" && a.HasValue && a.Segments.Count == 1 && !a.Segments[0].IsCode)
                {
                    context = a.Segments[0].Text.Trim();
                    if (context.Length == 0 || !CSharpScanner.IsIdentStart(context[0]) || CSharpScanner.ScanIdent(context, 0) != context.Length)
                    {
                        throw Parse($"'{context}' is not a valid name; use e.g. context=\"error\".", a.Segments[0].Start, System.Math.Max(1, a.Segments[0].Text.Length));
                    }
                }
                else
                {
                    throw Unsupported($"'{a.Name}' is not supported here; use <template slot=\"Fallback\" context=\"error\">.", a.Start, a.Name.Length);
                }
            }

            if (slot is null || !slot.HasValue || slot.Segments.Count != 1 || slot.Segments[0].IsCode || slot.Segments[0].Text.Trim() != "Fallback")
            {
                throw Structure("<ErrorBoundary> only takes a <template slot=\"Fallback\">.", t.Start, t.Tag.Length + 1);
            }

            if (fallback is not null)
            {
                throw Structure("Slot 'Fallback' is given more than once.", t.Start, t.Tag.Length + 1);
            }

            fallback = t;
        }

        if (fallback is null)
        {
            throw Structure("<ErrorBoundary> needs a <template slot=\"Fallback\" context=\"error\"> to show when something fails.", el.Start, el.Tag.Length + 1);
        }

        var body = SingleRoot(content, "<ErrorBoundary> content", el.Start)
            ?? throw Structure("<ErrorBoundary> must contain exactly one root node besides the Fallback template.", el.Start, el.Tag.Length + 1);
        var fallbackBody = SingleRoot(fallback.Children, "The Fallback template", fallback.Start)
            ?? throw Structure("The Fallback template must contain exactly one root node.", fallback.Start, fallback.Tag.Length + 1);

        sb.Append(H).Append("ErrorBoundary(() => ");
        EmitNode(body, nodePosition: true);
        sb.Append(", (global::NetWasm.UI.BoundaryError ").Append(context).Append(") => ");
        EmitNode(fallbackBody, nodePosition: true);
        sb.Append(')');
    }

    /// <summary>
    /// <c>&lt;Suspense&gt;content&lt;template slot="Fallback"&gt;…&lt;/template&gt;&lt;/Suspense&gt;</c>
    /// becomes <c>Html.Suspense(() =&gt; content, () =&gt; fallback)</c>.
    /// </summary>
    private void EmitSuspense(TElement el)
    {
        if (el.Attributes.Count > 0)
        {
            var a = el.Attributes[0];
            throw Unsupported($"'{a.Name}' is not supported on <Suspense>.", a.Start, a.Name.Length);
        }

        TElement? fallback = null;
        var content = new List<TNode>();
        foreach (var child in Trim(el.Children))
        {
            if (child is not TElement { Tag: "template" } t)
            {
                content.Add(child);
                continue;
            }

            var slot = t.Attributes.Count == 1 ? t.Attributes[0] : null;
            if (slot is null || slot.Name != "slot" || !slot.HasValue || slot.Segments.Count != 1 || slot.Segments[0].IsCode || slot.Segments[0].Text.Trim() != "Fallback")
            {
                throw Structure("<Suspense> only takes a <template slot=\"Fallback\">.", t.Start, t.Tag.Length + 1);
            }

            if (fallback is not null)
            {
                throw Structure("Slot 'Fallback' is given more than once.", t.Start, t.Tag.Length + 1);
            }

            fallback = t;
        }

        if (fallback is null)
        {
            throw Structure("<Suspense> needs a <template slot=\"Fallback\"> to show while loading.", el.Start, el.Tag.Length + 1);
        }

        var body = SingleRoot(content, "<Suspense> content", el.Start)
            ?? throw Structure("<Suspense> must contain exactly one root node besides the Fallback template.", el.Start, el.Tag.Length + 1);
        var fallbackBody = SingleRoot(fallback.Children, "The Fallback template", fallback.Start)
            ?? throw Structure("The Fallback template must contain exactly one root node.", fallback.Start, fallback.Tag.Length + 1);

        sb.Append(H).Append("Suspense(() => ");
        EmitNode(body, nodePosition: true);
        sb.Append(", () => ");
        EmitNode(fallbackBody, nodePosition: true);
        sb.Append(')');
    }

    private void EmitLink(TElement el, TAttribute? skip)
    {
        TAttribute? href = null;
        TAttribute? active = null;
        foreach (var a in el.Attributes)
        {
            if (a.Name == "href")
            {
                href = a;
            }
            else if (a.Name == "activeClass" && el.Tag == "NavLink")
            {
                active = a;
            }
        }

        if (href is null || !href.HasValue)
        {
            throw Structure($"<{el.Tag}> needs an 'href'.", el.Start, el.Tag.Length + 1);
        }

        var refName = RefOf(el, "global::NetWasm.UI.Element");
        if (refName is not null)
        {
            sb.Append('(').Append(refName).Append(" = ");
        }

        sb.Append(H).Append(el.Tag).Append('(');
        EmitPropValue(href);
        if (el.Tag == "NavLink")
        {
            sb.Append(", ");
            if (active is null)
            {
                sb.Append("\"active\"");
            }
            else
            {
                EmitPropValue(active);
            }
        }

        var rest = new TElement(el.Tag);
        foreach (var a in el.Attributes)
        {
            if (a != href && a != active && a != skip)
            {
                rest.Attributes.Add(a);
            }
        }

        EmitAttributes(rest, null);
        EmitChildren(el.Children);
        sb.Append(')');
        if (refName is not null)
        {
            sb.Append(')');
        }
    }

    private void EmitIf(TIf node)
    {
        var bodies = new List<TNode>();
        var hasElse = false;
        foreach (var b in node.Branches)
        {
            bodies.Add(SingleRoot(b.Body, b.Condition is null ? "An 'else' block" : "An '@if' block", b.Start)
                ?? throw Structure((b.Condition is null ? "An 'else' block" : "An '@if' block") + " must contain exactly one element.", b.Start, 2));
            hasElse |= b.Condition is null;
        }

        if (node.Branches.Count == 1 || (node.Branches.Count == 2 && hasElse))
        {
            sb.Append(H).Append("When(() => ");
            User(node.Branches[0].Condition!);
            sb.Append(", () => ");
            EmitNode(bodies[0], nodePosition: true);
            if (hasElse)
            {
                sb.Append(", () => ");
                EmitNode(bodies[1], nodePosition: true);
            }

            sb.Append(node.AnimateExit ? ").AnimateExit()" : ")");
            return;
        }

        // else-if chain: one selector (each condition evaluated once per change), one Show per branch.
        sb.Append(R).Append(node.AnimateExit ? "AnimatedChain(() => " : "Chain(() => ");
        for (var i = 0; i < node.Branches.Count; i++)
        {
            var c = node.Branches[i].Condition;
            if (c is null)
            {
                sb.Append(i.ToString(CultureInfo.InvariantCulture));
                break;
            }

            sb.Append('(');
            User(c);
            sb.Append(") ? ").Append(i.ToString(CultureInfo.InvariantCulture)).Append(" : ");
            if (i == node.Branches.Count - 1)
            {
                sb.Append("-1");
            }
        }

        for (var i = 0; i < bodies.Count; i++)
        {
            sb.Append(", () => ");
            EmitNode(bodies[i], nodePosition: true);
        }

        sb.Append(')');
    }

    private void EmitForeach(TForeach node)
    {
        var body = SingleRoot(node.Body, "An '@foreach' block", node.Start)
            ?? throw Structure("An '@foreach' block must contain exactly one element.", node.Start, 8);

        TAttribute? key = null;
        if (body is TElement el)
        {
            foreach (var a in el.Attributes)
            {
                if (a.Name == "@key")
                {
                    key = a;
                }
            }
        }

        if (body is TElement { IsComponent: false } rows)
        {
            EmitRows(node, rows, key);
            return;
        }

        var param = node.Type is null ? node.Variable : "(" + node.Type + " " + node.Variable + ")";
        sb.Append(R).Append("Each(() => ");
        User(node.Collection);
        if (key is not null)
        {
            sb.Append(", ").Append(param).Append(" => ");
            User(key.Code ?? throw Parse("'@key' needs a value.", key.Start, 4));
        }

        sb.Append(", ").Append(param).Append(" => ");
        if (body is TElement component)
        {
            EmitComponent(component, nodePosition: true, skip: key);
        }
        else
        {
            EmitNode(body, nodePosition: true);
        }

        sb.Append(')');
    }

    // ---- helpers ----

    private string? RefOf(TElement el, string type)
    {
        foreach (var a in el.Attributes)
        {
            if (a.Name != "@ref")
            {
                continue;
            }

            var name = a.Code?.Code.Trim() ?? string.Empty;
            if (name.Length == 0 || !CSharpScanner.IsIdentStart(name[0]) || CSharpScanner.ScanIdent(name, 0) != name.Length)
            {
                throw Parse("'@ref' must name a field, e.g. @ref=\"input\".", a.Start, a.Name.Length);
            }

            foreach (var (_, existing) in refs)
            {
                if (existing == name)
                {
                    return name;
                }
            }

            refs.Add((type, name));
            return name;
        }

        return null;
    }

    /// <summary>The single meaningful node of a body, or null if there are zero or several.</summary>
    private static TNode? SingleRoot(List<TNode> nodes, string what, int start)
    {
        var trimmed = Trim(nodes);
        if (trimmed.Count > 1)
        {
            throw Structure(what + " must have exactly one root node; wrap the content in an element.", trimmed[1].Start, 1);
        }

        return trimmed.Count == 1 ? trimmed[0] : null;
    }

    /// <summary>Drops text nodes that are empty after JSX-style whitespace collapsing.</summary>
    private static List<TNode> Trim(List<TNode> nodes)
    {
        var result = new List<TNode>();
        foreach (var n in nodes)
        {
            if (n is TText t)
            {
                var collapsed = Collapse(t.Raw);
                if (collapsed.Length == 0)
                {
                    continue;
                }
            }

            result.Add(n);
        }

        return result;
    }

    /// <summary>
    /// JSX whitespace: text on a single line is kept verbatim; otherwise each line is trimmed (except the
    /// leading whitespace of the first and trailing whitespace of the last), blank lines dropped, and the rest joined by a space.
    /// </summary>
    internal static string Collapse(string raw)
    {
        var parts = raw.Replace("\r", string.Empty).Split('\n');
        if (parts.Length == 1)
        {
            return raw;
        }

        var kept = new List<string>();
        for (var i = 0; i < parts.Length; i++)
        {
            var line = parts[i];
            if (i > 0)
            {
                line = line.TrimStart();
            }

            if (i < parts.Length - 1)
            {
                line = line.TrimEnd();
            }

            if (line.Trim().Length > 0)
            {
                kept.Add(line);
            }
        }

        return string.Join(" ", kept);
    }

    private static string Decode(string raw, int start)
    {
        Entities.Decode(raw, start); // reports unknown entities at their exact position in the template
        return Entities.Decode(Collapse(raw), start);
    }

    internal static string Literal(string value)
    {
        var b = new StringBuilder(value.Length + 2);
        b.Append('"');
        foreach (var c in value)
        {
            switch (c)
            {
                case '"': b.Append("\\\""); break;
                case '\\': b.Append("\\\\"); break;
                case '\n': b.Append("\\n"); break;
                case '\r': b.Append("\\r"); break;
                case '\t': b.Append("\\t"); break;
                case '\0': b.Append("\\0"); break;
                default:
                    if (char.IsControl(c) || c == '\u2028' || c == '\u2029')
                    {
                        b.Append("\\u").Append(((int)c).ToString("x4", CultureInfo.InvariantCulture));
                    }
                    else
                    {
                        b.Append(c);
                    }

                    break;
            }
        }

        b.Append('"');
        return b.ToString();
    }

    private void User(Segment seg) => User(new Directive(seg.Text, seg.Start));

    private void User(Directive d) => User(d, string.Empty, string.Empty, sb);

    /// <summary>
    /// Emits user C# on its own lines under <c>#line N</c>, padded so that its columns match the template;
    /// compiler errors then point straight into the .nwui file.
    /// </summary>
    private void User(Directive d, string prefix, string suffix, StringBuilder target)
    {
        var (line, col) = lines.Position(d.Start);
        target.Append('\n');
        target.Append("#line ").Append((line + 1).ToString(CultureInfo.InvariantCulture)).Append(" \"").Append(path).Append("\"\n");
        var pad = col - prefix.Length;
        if (pad > 0)
        {
            target.Append(' ', pad);
        }

        target.Append(prefix).Append(d.Code).Append(suffix).Append('\n');
        lineHidden = false;
        if (ReferenceEquals(target, sb))
        {
            Hidden();
        }
    }

    private void Hidden() => HiddenIn(sb);

    private void HiddenIn(StringBuilder target)
    {
        if (!lineHidden)
        {
            if (target.Length > 0 && target[target.Length - 1] != '\n')
            {
                target.Append('\n');
            }

            target.Append("#line hidden\n");
            lineHidden = true;
        }
    }

    private static TemplateException Parse(string message, int start, int length) => new("NWUI001", message, start, length);

    private static TemplateException Structure(string message, int start, int length) => new("NWUI002", message, start, length);

    private static TemplateException Unsupported(string message, int start, int length) => new("NWUI003", message, start, length);
}

/// <summary>Offset → (line, column), both 0-based.</summary>
internal sealed class LineMap
{
    private readonly List<int> starts = new() { 0 };

    public LineMap(string text)
    {
        for (var i = 0; i < text.Length; i++)
        {
            if (text[i] == '\n')
            {
                starts.Add(i + 1);
            }
        }
    }

    public (int Line, int Column) Position(int offset)
    {
        int lo = 0, hi = starts.Count - 1;
        while (lo < hi)
        {
            var mid = (lo + hi + 1) / 2;
            if (starts[mid] <= offset)
            {
                lo = mid;
            }
            else
            {
                hi = mid - 1;
            }
        }

        return (lo, offset - starts[lo]);
    }
}

internal static class Entities
{
    private static readonly Dictionary<string, string> Named = new()
    {
        ["amp"] = "&", ["lt"] = "<", ["gt"] = ">", ["quot"] = "\"", ["apos"] = "'", ["nbsp"] = "\u00a0",
        ["times"] = "\u00d7", ["middot"] = "\u00b7", ["copy"] = "\u00a9", ["hellip"] = "\u2026",
        ["mdash"] = "\u2014", ["ndash"] = "\u2013", ["larr"] = "\u2190", ["rarr"] = "\u2192",
        ["uarr"] = "\u2191", ["darr"] = "\u2193", ["minus"] = "\u2212", ["plusmn"] = "\u00b1",
        ["divide"] = "\u00f7", ["le"] = "\u2264", ["ge"] = "\u2265", ["ne"] = "\u2260",
        ["deg"] = "\u00b0", ["euro"] = "\u20ac", ["pound"] = "\u00a3", ["reg"] = "\u00ae",
        ["trade"] = "\u2122", ["sect"] = "\u00a7", ["para"] = "\u00b6", ["bull"] = "\u2022",
        ["laquo"] = "\u00ab", ["raquo"] = "\u00bb", ["lsquo"] = "\u2018", ["rsquo"] = "\u2019",
        ["ldquo"] = "\u201c", ["rdquo"] = "\u201d", ["check"] = "\u2713", ["shy"] = "\u00ad",
        ["zwj"] = "\u200d", ["zwnj"] = "\u200c", ["ensp"] = "\u2002", ["emsp"] = "\u2003", ["thinsp"] = "\u2009",
    };

    public static string Decode(string text, int start)
    {
        if (text.IndexOf('&') < 0)
        {
            return text;
        }

        var b = new StringBuilder(text.Length);
        for (var i = 0; i < text.Length; i++)
        {
            var c = text[i];
            var semi = c == '&' ? text.IndexOf(';', i + 1) : -1;
            if (semi < 0 || semi - i > 10)
            {
                b.Append(c);
                continue;
            }

            var name = text.Substring(i + 1, semi - i - 1);
            if (name.Length > 1 && name[0] == '#')
            {
                var hex = name[1] is 'x' or 'X';
                if (int.TryParse(hex ? name.Substring(2) : name.Substring(1), hex ? NumberStyles.HexNumber : NumberStyles.Integer, CultureInfo.InvariantCulture, out var code)
                    && code >= 0 && code <= 0x10FFFF)
                {
                    b.Append(char.ConvertFromUtf32(code));
                    i = semi;
                    continue;
                }
            }
            else if (Named.TryGetValue(name, out var value))
            {
                b.Append(value);
                i = semi;
                continue;
            }
            else if (IsEntityName(name))
            {
                throw new TemplateException(
                    "NWUI001",
                    $"Unknown entity '&{name};'. Use a numeric reference (e.g. '&#8722;') or the character itself.",
                    start + i,
                    semi - i + 1);
            }

            b.Append(c);
        }

        return b.ToString();
    }

    private static bool IsEntityName(string name)
    {
        if (name.Length == 0 || !char.IsLetter(name[0]))
        {
            return false;
        }

        foreach (var ch in name)
        {
            if (!char.IsLetterOrDigit(ch))
            {
                return false;
            }
        }

        return true;
    }
}
