using System.Collections.Generic;
using System.Globalization;
using System.Text;

namespace NetWasm.UI.Generator;

/// <summary>Turns a parsed template into a C# partial class built on <c>NetWasm.UI.Html</c>.</summary>
internal sealed class TemplateEmitter
{
    private const string H = "global::NetWasm.UI.Html.";
    private const string R = "global::NetWasm.UI.TemplateRuntime.";

    private static readonly HashSet<string> BooleanAttributes = new(System.StringComparer.OrdinalIgnoreCase)
    {
        "disabled", "checked", "hidden", "readonly", "required", "selected", "multiple", "autofocus", "open",
    };

    private readonly LineMap lines;
    private readonly string path;
    private readonly ISet<string> reactiveProps;
    private readonly StringBuilder sb = new();
    private readonly List<(string Type, string Name)> refs = new();
    private bool lineHidden;

    private TemplateEmitter(string text, string path, ISet<string> reactiveProps)
    {
        lines = new LineMap(text);
        this.path = path.Replace("\"", string.Empty);
        this.reactiveProps = reactiveProps;
    }

    /// <param name="reactiveProps"><c>Component.Prop</c> names whose type is <c>Prop&lt;T&gt;</c>; the parent passes those as getters.</param>
    public static string Emit(TemplateFile file, string text, string path, string? ns, string className, ISet<string>? reactiveProps = null)
    {
        var e = new TemplateEmitter(text, path, reactiveProps ?? new HashSet<string>());
        return e.EmitFile(file, ns, className);
    }

    private string EmitFile(TemplateFile file, string? ns, string className)
    {
        var root = SingleRoot(file.Nodes, "A template", 0);
        if (root is null)
        {
            throw new TemplateException("NWUI002", "A template must contain exactly one root element.", 0, 1);
        }

        // Build the body first so @ref fields are known.
        var header = new StringBuilder();
        header.Append("// <auto-generated/>\n#nullable enable\n#pragma warning disable CS1591\n");
        header.Append("using System.Collections.Generic;\nusing NetWasm.UI;\nusing NetWasm.UI.Reactive;\nusing NetWasm.UI.Routing;\nusing static NetWasm.UI.Html;\n");

        var bodyStart = sb.Length;
        sb.Append("    protected override global::NetWasm.UI.Node Build()\n    {\n        OnInit();\n        return ");
        EmitNode(root, nodePosition: true);
        Hidden();
        sb.Append(";\n    }\n");
        var body = sb.ToString(bodyStart, sb.Length - bodyStart);
        sb.Length = bodyStart;

        foreach (var u in file.Usings)
        {
            User(u, "using ", ";", header);
        }

        HiddenIn(header);
        if (ns is { Length: > 0 })
        {
            header.Append("namespace ").Append(ns).Append(";\n");
        }

        header.Append("\npublic partial class ").Append(className).Append(" : global::NetWasm.UI.Component\n{\n");
        foreach (var (type, name) in refs)
        {
            header.Append("    private ").Append(type).Append(' ').Append(name).Append(" = null!;\n");
        }

        foreach (var p in file.Props)
        {
            header.Append("\n    public global::NetWasm.UI.Prop<");
            User(p.Type, string.Empty, string.Empty, header);
            HiddenIn(header);
            header.Append("    >");
            User(p.Name, string.Empty, string.Empty, header);
            HiddenIn(header);
            header.Append("    { get; set; }");
            if (p.Default is not null)
            {
                header.Append(" =");
                User(p.Default, string.Empty, string.Empty, header);
                HiddenIn(header);
            }

            header.Append(";\n");
        }

        header.Append("\n    /// <summary>Runs at the start of Build, inside the component's scope (Use/Provide/OnMount work here).</summary>\n");
        header.Append("    partial void OnInit();\n\n");
        header.Append(body);

        lineHidden = true;
        foreach (var block in file.CodeBlocks)
        {
            User(block, string.Empty, string.Empty, header);
        }

        header.Append("\n#line default\n}\n");
        return header.ToString();
    }

    // ---- nodes ----

    /// <summary>Emits a node as Content (inside an element) or as a Node (root / branch body).</summary>
    private void EmitNode(TNode node, bool nodePosition)
    {
        switch (node)
        {
            case TText t:
                var literal = Literal(Decode(t.Raw, t.Start));
                sb.Append(nodePosition ? H + "Text(" + literal + ")" : literal);
                break;
            case TExpr x:
                sb.Append(H).Append("Text(() => ");
                User(x.Code);
                sb.Append(')');
                break;
            case TRender r:
                sb.Append('(');
                User(r.Code);
                sb.Append(')');
                break;
            case TElement el when el.IsComponent:
                EmitComponent(el, nodePosition);
                break;
            case TElement el:
                EmitElement(el);
                break;
            case TIf i:
                if (nodePosition)
                {
                    throw Structure("'@if' cannot be the only content of a template or block; wrap it in an element.", i.Start, 3);
                }

                EmitIf(i);
                break;
            case TForeach f:
                if (nodePosition)
                {
                    throw Structure("'@foreach' cannot be the only content of a template or block; wrap it in an element.", f.Start, 8);
                }

                EmitForeach(f);
                break;
        }
    }

    private void EmitElement(TElement el, TAttribute? skip = null)
    {
        var refName = RefOf(el, "global::NetWasm.UI.Element");
        if (refName is not null)
        {
            sb.Append('(').Append(refName).Append(" = ");
        }

        sb.Append(H).Append("El(").Append(Literal(el.Tag));
        EmitAttributes(el, skip);
        EmitChildren(el.Children);
        sb.Append(')');
        if (refName is not null)
        {
            sb.Append(')');
        }
    }

    private void EmitChildren(List<TNode> children)
    {
        foreach (var child in Trim(children))
        {
            sb.Append(", ");
            EmitNode(child, nodePosition: false);
        }
    }

    private void EmitAttributes(TElement el, TAttribute? skip)
    {
        var handlers = new List<TAttribute>();
        foreach (var a in el.Attributes)
        {
            if (a == skip || a.Name == "@ref")
            {
                continue;
            }

            if (a.IsDirective)
            {
                if (a.Name == "@bind")
                {
                    sb.Append(", ").Append(H).Append("Spread(").Append(H).Append("Bind(");
                    User(a.Code!);
                    sb.Append("))");
                }
                else if (a.Name.StartsWith("@on", System.StringComparison.Ordinal) && a.Name.Length > 3)
                {
                    handlers.Add(a);
                }
                else if (a.Name == "@key")
                {
                    throw Structure("'@key' is only allowed on the root element of an '@foreach' body.", a.Start, a.Name.Length);
                }
                else
                {
                    throw Unsupported($"Unknown directive attribute '{a.Name}' (supported: @bind, @ref, @key, @on<event>[:preventDefault|:stopPropagation]).", a.Start, a.Name.Length);
                }

                continue;
            }

            sb.Append(", ");
            EmitAttribute(a);
        }

        EmitHandlers(handlers);
    }

    private void EmitAttribute(TAttribute a)
    {
        var name = a.Name;
        var isValue = name == "value";
        if (!a.HasValue)
        {
            sb.Append(H).Append("Attr(").Append(Literal(name)).Append(", \"\")");
            return;
        }

        var allLiteral = true;
        foreach (var seg in a.Segments)
        {
            allLiteral &= !seg.IsCode;
        }

        if (allLiteral)
        {
            var text = new StringBuilder();
            foreach (var seg in a.Segments)
            {
                text.Append(Decode(seg.Text, seg.Start));
            }

            sb.Append(H).Append(isValue ? "Value(" : "Attr(" + Literal(name) + ", ").Append(Literal(text.ToString())).Append(')');
            return;
        }

        if (a.Segments.Count == 1 && BooleanAttributes.Contains(name))
        {
            sb.Append(name == "checked" ? H + "Checked(() => " : "global::NetWasm.UI.Attr.Toggle(" + Literal(name) + ", () => ");
            User(a.Segments[0]);
            sb.Append(')');
            return;
        }

        sb.Append(H).Append(isValue ? "Value(() => " : "Attr(" + Literal(name) + ", () => ");
        EmitInterpolated(a.Segments);
        if (isValue)
        {
            sb.Append(" ?? \"\"");
        }

        sb.Append(')');
    }

    /// <summary>Emits a <c>string?</c> expression for literal text mixed with <c>@expr</c> pieces.</summary>
    private void EmitInterpolated(List<Segment> segments)
    {
        if (segments.Count == 1)
        {
            sb.Append(R).Append("Str(");
            User(segments[0]);
            sb.Append(')');
            return;
        }

        sb.Append("string.Concat(new string?[] { ");
        for (var i = 0; i < segments.Count; i++)
        {
            if (i > 0)
            {
                sb.Append(", ");
            }

            var seg = segments[i];
            if (seg.IsCode)
            {
                sb.Append(R).Append("Str(");
                User(seg);
                sb.Append(')');
            }
            else
            {
                sb.Append(Literal(Decode(seg.Text, seg.Start)));
            }
        }

        sb.Append(" })");
    }

    private void EmitHandlers(List<TAttribute> attrs)
    {
        var events = new List<string>();
        var handler = new Dictionary<string, TAttribute>();
        var flags = new Dictionary<string, int>();
        var first = new Dictionary<string, TAttribute>();
        foreach (var a in attrs)
        {
            var spec = a.Name.Substring(3);
            var colon = spec.IndexOf(':');
            var evt = colon < 0 ? spec : spec.Substring(0, colon);
            if (evt.Length == 0)
            {
                throw Parse($"Missing event name in '{a.Name}'.", a.Start, a.Name.Length);
            }

            if (!first.ContainsKey(evt))
            {
                first[evt] = a;
                events.Add(evt);
                flags[evt] = evt == "submit" ? 1 : 0;
            }

            if (colon < 0)
            {
                if (a.Code is null)
                {
                    throw Parse($"'{a.Name}' needs a handler, e.g. {a.Name}=\"() => ...\".", a.Start, a.Name.Length);
                }

                if (handler.ContainsKey(evt))
                {
                    throw Structure($"Duplicate handler for '{evt}'.", a.Start, a.Name.Length);
                }

                handler[evt] = a;
                continue;
            }

            var modifier = spec.Substring(colon + 1);
            int bit;
            if (modifier == "preventDefault")
            {
                bit = 1;
            }
            else if (modifier == "stopPropagation")
            {
                bit = 2;
            }
            else
            {
                throw Unsupported($"Unknown event modifier ':{modifier}' (supported: :preventDefault, :stopPropagation).", a.Start, a.Name.Length);
            }

            var on = true;
            if (a.Code is not null)
            {
                var v = a.Code.Code.Trim();
                if (v != "true" && v != "false")
                {
                    throw Unsupported($"'{a.Name}' must be \"true\" or \"false\".", a.Start, a.Name.Length);
                }

                on = v == "true";
            }

            flags[evt] = on ? flags[evt] | bit : flags[evt] & ~bit;
        }

        foreach (var evt in events)
        {
            if (!handler.TryGetValue(evt, out var a))
            {
                var f = first[evt];
                throw Structure($"Modifier '{f.Name}' without an '@on{evt}' handler.", f.Start, f.Name.Length);
            }

            sb.Append(", ").Append(H).Append("On(").Append(Literal(evt)).Append(", ");
            User(a.Code!);
            sb.Append(", (global::NetWasm.UI.Dom.ListenerFlags)").Append(flags[evt].ToString(CultureInfo.InvariantCulture)).Append(')');
        }
    }

    private void EmitComponent(TElement el, bool nodePosition, TAttribute? skip = null)
    {
        if (el.Tag is "Link" or "NavLink")
        {
            EmitLink(el, skip);
            return;
        }

        if (el.Tag == "ErrorBoundary")
        {
            if (nodePosition)
            {
                throw Structure("<ErrorBoundary> cannot be the only content of a template or block; wrap it in an element.", el.Start, el.Tag.Length + 1);
            }

            EmitErrorBoundary(el);
            return;
        }

        var slots = SlotsOf(el);
        var refName = RefOf(el, el.Tag);
        if (refName is not null)
        {
            sb.Append('(').Append(refName).Append(" = ");
        }

        sb.Append("new ").Append(el.Tag).Append(" {");
        var any = false;
        foreach (var a in el.Attributes)
        {
            if (a == skip || a.Name == "@ref")
            {
                continue;
            }

            if (a.IsDirective)
            {
                throw Unsupported($"'{a.Name}' is not supported on components.", a.Start, a.Name.Length);
            }

            sb.Append(any ? "," : string.Empty);
            any = true;
            User(new Directive(a.Name, a.Start));
            sb.Append(" = ");
            if (IsReactiveProp(el.Tag, a.Name))
            {
                EmitReactivePropValue(a);
            }
            else
            {
                EmitPropValue(a);
            }
        }

        foreach (var (name, start, body) in slots)
        {
            sb.Append(any ? "," : string.Empty);
            any = true;
            User(new Directive(name, start));
            sb.Append(" = new global::NetWasm.UI.Slot(() => new global::NetWasm.UI.Content[] {");
            for (var i = 0; i < body.Count; i++)
            {
                sb.Append(i == 0 ? " " : ", ");
                EmitNode(body[i], nodePosition: false);
            }

            sb.Append(" })");
        }

        sb.Append(any ? " }" : "}");
        if (refName is not null)
        {
            sb.Append(')');
        }

        if (nodePosition)
        {
            sb.Append(".Render()");
        }
    }

    /// <summary>
    /// A component's child content: <c>&lt;template slot="Name"&gt;…&lt;/template&gt;</c> children fill the
    /// <c>Name</c> slot; everything else goes to <c>ChildContent</c>.
    /// </summary>
    private static List<(string Name, int Start, List<TNode> Body)> SlotsOf(TElement el)
    {
        var slots = new List<(string Name, int Start, List<TNode> Body)>();
        var loose = new List<TNode>();
        foreach (var child in Trim(el.Children))
        {
            if (child is not TElement { Tag: "template" } t)
            {
                loose.Add(child);
                continue;
            }

            TAttribute? slot = null;
            foreach (var a in t.Attributes)
            {
                if (a.Name != "slot")
                {
                    throw Unsupported($"'{a.Name}' is not supported on a slot <template>; only 'slot' is.", a.Start, a.Name.Length);
                }

                slot = a;
            }

            if (slot is null || !slot.HasValue || slot.Segments.Count != 1 || slot.Segments[0].IsCode)
            {
                throw Structure("A <template> inside a component needs slot=\"Name\".", t.Start, t.Tag.Length + 1);
            }

            var name = slot.Segments[0].Text.Trim();
            if (name.Length == 0 || !CSharpScanner.IsIdentStart(name[0]) || CSharpScanner.ScanIdent(name, 0) != name.Length)
            {
                throw Parse($"'{name}' is not a valid slot name; use a property name like slot=\"Header\".", slot.Segments[0].Start, System.Math.Max(1, slot.Segments[0].Text.Length));
            }

            Add(name, slot.Segments[0].Start, Trim(t.Children));
        }

        if (loose.Count > 0)
        {
            Add("ChildContent", loose[0].Start, loose);
        }

        return slots;

        void Add(string name, int start, List<TNode> body)
        {
            foreach (var s in slots)
            {
                if (s.Name == name)
                {
                    var hint = name == "ChildContent" ? " (loose child content fills 'ChildContent')" : string.Empty;
                    throw Structure($"Slot '{name}' is given more than once{hint}.", start, 1);
                }
            }

            slots.Add((name, start, body));
        }
    }

    private bool IsReactiveProp(string tag, string prop)
    {
        var dot = tag.LastIndexOf('.');
        return reactiveProps.Contains((dot < 0 ? tag : tag.Substring(dot + 1)) + "." + prop);
    }

    /// <summary>
    /// For a <c>Prop&lt;T&gt;</c> prop, <c>Prop="@expr"</c> becomes <c>new(() => expr)</c> so the child re-reads it
    /// (and tracks what it reads). Literals and bare props still convert implicitly from the value.
    /// </summary>
    private void EmitReactivePropValue(TAttribute a)
    {
        var hasCode = false;
        foreach (var seg in a.Segments)
        {
            hasCode |= seg.IsCode;
        }

        if (!a.HasValue || !hasCode)
        {
            EmitPropValue(a);
            return;
        }

        sb.Append("new(() => ");
        EmitPropValue(a);
        sb.Append(')');
    }

    /// <summary>Literal props are strings; <c>Prop="@expr"</c> passes the expression as-is; a bare <c>Prop</c> is <c>true</c>.</summary>
    private void EmitPropValue(TAttribute a)
    {
        if (!a.HasValue)
        {
            sb.Append("true");
            return;
        }

        if (a.Segments.Count == 1 && a.Segments[0].IsCode)
        {
            User(a.Segments[0]);
            return;
        }

        var allLiteral = true;
        foreach (var seg in a.Segments)
        {
            allLiteral &= !seg.IsCode;
        }

        if (allLiteral)
        {
            var text = new StringBuilder();
            foreach (var seg in a.Segments)
            {
                text.Append(Decode(seg.Text, seg.Start));
            }

            sb.Append(Literal(text.ToString()));
            return;
        }

        sb.Append('(');
        EmitInterpolated(a.Segments);
        sb.Append(" ?? \"\")");
    }

    /// <summary>
    /// <c>&lt;ErrorBoundary&gt;content&lt;template slot="Fallback" context="error"&gt;…&lt;/template&gt;&lt;/ErrorBoundary&gt;</c>
    /// becomes <c>Html.ErrorBoundary(() =&gt; content, (BoundaryError error) =&gt; fallback)</c>.
    /// </summary>
    private void EmitErrorBoundary(TElement el)
    {
        if (el.Attributes.Count > 0)
        {
            var a = el.Attributes[0];
            throw Unsupported($"'{a.Name}' is not supported on <ErrorBoundary>.", a.Start, a.Name.Length);
        }

        TElement? fallback = null;
        var context = "error";
        var content = new List<TNode>();
        foreach (var child in Trim(el.Children))
        {
            if (child is not TElement { Tag: "template" } t)
            {
                content.Add(child);
                continue;
            }

            TAttribute? slot = null;
            foreach (var a in t.Attributes)
            {
                if (a.Name == "slot")
                {
                    slot = a;
                }
                else if (a.Name == "context" && a.HasValue && a.Segments.Count == 1 && !a.Segments[0].IsCode)
                {
                    context = a.Segments[0].Text.Trim();
                    if (context.Length == 0 || !CSharpScanner.IsIdentStart(context[0]) || CSharpScanner.ScanIdent(context, 0) != context.Length)
                    {
                        throw Parse($"'{context}' is not a valid name; use e.g. context=\"error\".", a.Segments[0].Start, System.Math.Max(1, a.Segments[0].Text.Length));
                    }
                }
                else
                {
                    throw Unsupported($"'{a.Name}' is not supported here; use <template slot=\"Fallback\" context=\"error\">.", a.Start, a.Name.Length);
                }
            }

            if (slot is null || !slot.HasValue || slot.Segments.Count != 1 || slot.Segments[0].IsCode || slot.Segments[0].Text.Trim() != "Fallback")
            {
                throw Structure("<ErrorBoundary> only takes a <template slot=\"Fallback\">.", t.Start, t.Tag.Length + 1);
            }

            if (fallback is not null)
            {
                throw Structure("Slot 'Fallback' is given more than once.", t.Start, t.Tag.Length + 1);
            }

            fallback = t;
        }

        if (fallback is null)
        {
            throw Structure("<ErrorBoundary> needs a <template slot=\"Fallback\" context=\"error\"> to show when something fails.", el.Start, el.Tag.Length + 1);
        }

        var body = SingleRoot(content, "<ErrorBoundary> content", el.Start)
            ?? throw Structure("<ErrorBoundary> must contain exactly one root node besides the Fallback template.", el.Start, el.Tag.Length + 1);
        var fallbackBody = SingleRoot(fallback.Children, "The Fallback template", fallback.Start)
            ?? throw Structure("The Fallback template must contain exactly one root node.", fallback.Start, fallback.Tag.Length + 1);

        sb.Append(H).Append("ErrorBoundary(() => ");
        EmitNode(body, nodePosition: true);
        sb.Append(", (global::NetWasm.UI.BoundaryError ").Append(context).Append(") => ");
        EmitNode(fallbackBody, nodePosition: true);
        sb.Append(')');
    }

    private void EmitLink(TElement el, TAttribute? skip)
    {
        TAttribute? href = null;
        TAttribute? active = null;
        foreach (var a in el.Attributes)
        {
            if (a.Name == "href")
            {
                href = a;
            }
            else if (a.Name == "activeClass" && el.Tag == "NavLink")
            {
                active = a;
            }
        }

        if (href is null || !href.HasValue)
        {
            throw Structure($"<{el.Tag}> needs an 'href'.", el.Start, el.Tag.Length + 1);
        }

        var refName = RefOf(el, "global::NetWasm.UI.Element");
        if (refName is not null)
        {
            sb.Append('(').Append(refName).Append(" = ");
        }

        sb.Append(H).Append(el.Tag).Append('(');
        EmitPropValue(href);
        if (el.Tag == "NavLink")
        {
            sb.Append(", ");
            if (active is null)
            {
                sb.Append("\"active\"");
            }
            else
            {
                EmitPropValue(active);
            }
        }

        var rest = new TElement(el.Tag);
        foreach (var a in el.Attributes)
        {
            if (a != href && a != active && a != skip)
            {
                rest.Attributes.Add(a);
            }
        }

        EmitAttributes(rest, null);
        EmitChildren(el.Children);
        sb.Append(')');
        if (refName is not null)
        {
            sb.Append(')');
        }
    }

    private void EmitIf(TIf node)
    {
        var bodies = new List<TNode>();
        var hasElse = false;
        foreach (var b in node.Branches)
        {
            bodies.Add(SingleRoot(b.Body, b.Condition is null ? "An 'else' block" : "An '@if' block", b.Start)
                ?? throw Structure((b.Condition is null ? "An 'else' block" : "An '@if' block") + " must contain exactly one element.", b.Start, 2));
            hasElse |= b.Condition is null;
        }

        if (node.Branches.Count == 1 || (node.Branches.Count == 2 && hasElse))
        {
            sb.Append(H).Append("When(() => ");
            User(node.Branches[0].Condition!);
            sb.Append(", () => ");
            EmitNode(bodies[0], nodePosition: true);
            if (hasElse)
            {
                sb.Append(", () => ");
                EmitNode(bodies[1], nodePosition: true);
            }

            sb.Append(')');
            return;
        }

        // else-if chain: one selector (each condition evaluated once per change), one Show per branch.
        sb.Append(R).Append("Chain(() => ");
        for (var i = 0; i < node.Branches.Count; i++)
        {
            var c = node.Branches[i].Condition;
            if (c is null)
            {
                sb.Append(i.ToString(CultureInfo.InvariantCulture));
                break;
            }

            sb.Append('(');
            User(c);
            sb.Append(") ? ").Append(i.ToString(CultureInfo.InvariantCulture)).Append(" : ");
            if (i == node.Branches.Count - 1)
            {
                sb.Append("-1");
            }
        }

        for (var i = 0; i < bodies.Count; i++)
        {
            sb.Append(", () => ");
            EmitNode(bodies[i], nodePosition: true);
        }

        sb.Append(')');
    }

    private void EmitForeach(TForeach node)
    {
        var body = SingleRoot(node.Body, "An '@foreach' block", node.Start)
            ?? throw Structure("An '@foreach' block must contain exactly one element.", node.Start, 8);

        TAttribute? key = null;
        if (body is TElement el)
        {
            foreach (var a in el.Attributes)
            {
                if (a.Name == "@key")
                {
                    key = a;
                }
            }
        }

        var param = node.Type is null ? node.Variable : "(" + node.Type + " " + node.Variable + ")";
        sb.Append(R).Append("Each(() => ");
        User(node.Collection);
        if (key is not null)
        {
            sb.Append(", ").Append(param).Append(" => ");
            User(key.Code ?? throw Parse("'@key' needs a value.", key.Start, 4));
        }

        sb.Append(", ").Append(param).Append(" => ");
        if (body is TElement root)
        {
            if (root.IsComponent)
            {
                EmitComponent(root, nodePosition: true, skip: key);
            }
            else
            {
                EmitElement(root, key);
            }
        }
        else
        {
            EmitNode(body, nodePosition: true);
        }

        sb.Append(')');
    }

    // ---- helpers ----

    private string? RefOf(TElement el, string type)
    {
        foreach (var a in el.Attributes)
        {
            if (a.Name != "@ref")
            {
                continue;
            }

            var name = a.Code?.Code.Trim() ?? string.Empty;
            if (name.Length == 0 || !CSharpScanner.IsIdentStart(name[0]) || CSharpScanner.ScanIdent(name, 0) != name.Length)
            {
                throw Parse("'@ref' must name a field, e.g. @ref=\"input\".", a.Start, a.Name.Length);
            }

            foreach (var (_, existing) in refs)
            {
                if (existing == name)
                {
                    return name;
                }
            }

            refs.Add((type, name));
            return name;
        }

        return null;
    }

    /// <summary>The single meaningful node of a body, or null if there are zero or several.</summary>
    private static TNode? SingleRoot(List<TNode> nodes, string what, int start)
    {
        var trimmed = Trim(nodes);
        if (trimmed.Count > 1)
        {
            throw Structure(what + " must have exactly one root node; wrap the content in an element.", trimmed[1].Start, 1);
        }

        return trimmed.Count == 1 ? trimmed[0] : null;
    }

    /// <summary>Drops text nodes that are empty after JSX-style whitespace collapsing.</summary>
    private static List<TNode> Trim(List<TNode> nodes)
    {
        var result = new List<TNode>();
        foreach (var n in nodes)
        {
            if (n is TText t)
            {
                var collapsed = Collapse(t.Raw);
                if (collapsed.Length == 0)
                {
                    continue;
                }
            }

            result.Add(n);
        }

        return result;
    }

    /// <summary>
    /// JSX whitespace: text on a single line is kept verbatim; otherwise each line is trimmed (except the
    /// leading whitespace of the first and trailing whitespace of the last), blank lines dropped, and the rest joined by a space.
    /// </summary>
    internal static string Collapse(string raw)
    {
        var parts = raw.Replace("\r", string.Empty).Split('\n');
        if (parts.Length == 1)
        {
            return raw;
        }

        var kept = new List<string>();
        for (var i = 0; i < parts.Length; i++)
        {
            var line = parts[i];
            if (i > 0)
            {
                line = line.TrimStart();
            }

            if (i < parts.Length - 1)
            {
                line = line.TrimEnd();
            }

            if (line.Trim().Length > 0)
            {
                kept.Add(line);
            }
        }

        return string.Join(" ", kept);
    }

    private static string Decode(string raw, int start)
    {
        Entities.Decode(raw, start); // reports unknown entities at their exact position in the template
        return Entities.Decode(Collapse(raw), start);
    }

    internal static string Literal(string value)
    {
        var b = new StringBuilder(value.Length + 2);
        b.Append('"');
        foreach (var c in value)
        {
            switch (c)
            {
                case '"': b.Append("\\\""); break;
                case '\\': b.Append("\\\\"); break;
                case '\n': b.Append("\\n"); break;
                case '\r': b.Append("\\r"); break;
                case '\t': b.Append("\\t"); break;
                case '\0': b.Append("\\0"); break;
                default:
                    if (char.IsControl(c) || c == '\u2028' || c == '\u2029')
                    {
                        b.Append("\\u").Append(((int)c).ToString("x4", CultureInfo.InvariantCulture));
                    }
                    else
                    {
                        b.Append(c);
                    }

                    break;
            }
        }

        b.Append('"');
        return b.ToString();
    }

    private void User(Segment seg) => User(new Directive(seg.Text, seg.Start));

    private void User(Directive d) => User(d, string.Empty, string.Empty, sb);

    /// <summary>
    /// Emits user C# on its own lines under <c>#line N</c>, padded so that its columns match the template;
    /// compiler errors then point straight into the .nwui file.
    /// </summary>
    private void User(Directive d, string prefix, string suffix, StringBuilder target)
    {
        var (line, col) = lines.Position(d.Start);
        target.Append('\n');
        target.Append("#line ").Append((line + 1).ToString(CultureInfo.InvariantCulture)).Append(" \"").Append(path).Append("\"\n");
        var pad = col - prefix.Length;
        if (pad > 0)
        {
            target.Append(' ', pad);
        }

        target.Append(prefix).Append(d.Code).Append(suffix).Append('\n');
        lineHidden = false;
        if (ReferenceEquals(target, sb))
        {
            Hidden();
        }
    }

    private void Hidden() => HiddenIn(sb);

    private void HiddenIn(StringBuilder target)
    {
        if (!lineHidden)
        {
            if (target.Length > 0 && target[target.Length - 1] != '\n')
            {
                target.Append('\n');
            }

            target.Append("#line hidden\n");
            lineHidden = true;
        }
    }

    private static TemplateException Parse(string message, int start, int length) => new("NWUI001", message, start, length);

    private static TemplateException Structure(string message, int start, int length) => new("NWUI002", message, start, length);

    private static TemplateException Unsupported(string message, int start, int length) => new("NWUI003", message, start, length);
}

/// <summary>Offset → (line, column), both 0-based.</summary>
internal sealed class LineMap
{
    private readonly List<int> starts = new() { 0 };

    public LineMap(string text)
    {
        for (var i = 0; i < text.Length; i++)
        {
            if (text[i] == '\n')
            {
                starts.Add(i + 1);
            }
        }
    }

    public (int Line, int Column) Position(int offset)
    {
        int lo = 0, hi = starts.Count - 1;
        while (lo < hi)
        {
            var mid = (lo + hi + 1) / 2;
            if (starts[mid] <= offset)
            {
                lo = mid;
            }
            else
            {
                hi = mid - 1;
            }
        }

        return (lo, offset - starts[lo]);
    }
}

internal static class Entities
{
    private static readonly Dictionary<string, string> Named = new()
    {
        ["amp"] = "&", ["lt"] = "<", ["gt"] = ">", ["quot"] = "\"", ["apos"] = "'", ["nbsp"] = "\u00a0",
        ["times"] = "\u00d7", ["middot"] = "\u00b7", ["copy"] = "\u00a9", ["hellip"] = "\u2026",
        ["mdash"] = "\u2014", ["ndash"] = "\u2013", ["larr"] = "\u2190", ["rarr"] = "\u2192",
        ["uarr"] = "\u2191", ["darr"] = "\u2193", ["minus"] = "\u2212", ["plusmn"] = "\u00b1",
        ["divide"] = "\u00f7", ["le"] = "\u2264", ["ge"] = "\u2265", ["ne"] = "\u2260",
        ["deg"] = "\u00b0", ["euro"] = "\u20ac", ["pound"] = "\u00a3", ["reg"] = "\u00ae",
        ["trade"] = "\u2122", ["sect"] = "\u00a7", ["para"] = "\u00b6", ["bull"] = "\u2022",
        ["laquo"] = "\u00ab", ["raquo"] = "\u00bb", ["lsquo"] = "\u2018", ["rsquo"] = "\u2019",
        ["ldquo"] = "\u201c", ["rdquo"] = "\u201d", ["check"] = "\u2713", ["shy"] = "\u00ad",
        ["zwj"] = "\u200d", ["zwnj"] = "\u200c", ["ensp"] = "\u2002", ["emsp"] = "\u2003", ["thinsp"] = "\u2009",
    };

    public static string Decode(string text, int start)
    {
        if (text.IndexOf('&') < 0)
        {
            return text;
        }

        var b = new StringBuilder(text.Length);
        for (var i = 0; i < text.Length; i++)
        {
            var c = text[i];
            var semi = c == '&' ? text.IndexOf(';', i + 1) : -1;
            if (semi < 0 || semi - i > 10)
            {
                b.Append(c);
                continue;
            }

            var name = text.Substring(i + 1, semi - i - 1);
            if (name.Length > 1 && name[0] == '#')
            {
                var hex = name[1] is 'x' or 'X';
                if (int.TryParse(hex ? name.Substring(2) : name.Substring(1), hex ? NumberStyles.HexNumber : NumberStyles.Integer, CultureInfo.InvariantCulture, out var code)
                    && code >= 0 && code <= 0x10FFFF)
                {
                    b.Append(char.ConvertFromUtf32(code));
                    i = semi;
                    continue;
                }
            }
            else if (Named.TryGetValue(name, out var value))
            {
                b.Append(value);
                i = semi;
                continue;
            }
            else if (IsEntityName(name))
            {
                throw new TemplateException(
                    "NWUI001",
                    $"Unknown entity '&{name};'. Use a numeric reference (e.g. '&#8722;') or the character itself.",
                    start + i,
                    semi - i + 1);
            }

            b.Append(c);
        }

        return b.ToString();
    }

    private static bool IsEntityName(string name)
    {
        if (name.Length == 0 || !char.IsLetter(name[0]))
        {
            return false;
        }

        foreach (var ch in name)
        {
            if (!char.IsLetterOrDigit(ch))
            {
                return false;
            }
        }

        return true;
    }
}
