using System;
using Microsoft.CodeAnalysis;

namespace NetWasm.UI.Generator;

/// <summary>
/// In Debug builds of apps that reference NetWasm.UI.Browser, emits a module initializer that calls
/// <c>DevReload.Install()</c>, so the dev server can keep signal values across reloads. Release builds get
/// nothing, so the code is trimmed from their Wasm. <c>NetWasmUIDevState</c> = <c>true</c>/<c>false</c> overrides.
/// </summary>
[Generator(LanguageNames.CSharp)]
public sealed class DevStateGenerator : IIncrementalGenerator
{
    private const string DevReloadType = "NetWasm.UI.Browser.DevReload";

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var enabled = context.AnalyzerConfigOptionsProvider.Select(static (options, _) =>
        {
            options.GlobalOptions.TryGetValue("build_property.NetWasmUIDevState", out var setting);
            if (!string.IsNullOrEmpty(setting))
            {
                return string.Equals(setting, "true", StringComparison.OrdinalIgnoreCase);
            }

            options.GlobalOptions.TryGetValue("build_property.Configuration", out var configuration);
            return string.Equals(configuration, "Debug", StringComparison.OrdinalIgnoreCase);
        });

        // Only when DevReload comes from a reference: never inside NetWasm.UI.Browser itself.
        var referencesBrowser = context.CompilationProvider.Select(static (compilation, _) =>
            compilation.GetTypeByMetadataName(DevReloadType) is { } type
            && !SymbolEqualityComparer.Default.Equals(type.ContainingAssembly, compilation.Assembly));

        context.RegisterSourceOutput(enabled.Combine(referencesBrowser), static (spc, pair) =>
        {
            if (pair.Left && pair.Right)
            {
                spc.AddSource("NetWasm.UI.DevState.g.cs", Source);
            }
        });
    }

    private const string Source = """
        // <auto-generated/>
        // Debug build: lets the NetWasm.UI dev server keep signal values across reloads.
        // Set <NetWasmUIDevState>false</NetWasmUIDevState> to turn it off.
        #pragma warning disable CA2255
        namespace NetWasm.UI.Generated
        {
            internal static class DevStateInitializer
            {
                [global::System.Runtime.CompilerServices.ModuleInitializer]
                internal static void Initialize() => global::NetWasm.UI.Browser.DevReload.Install();
            }
        }

        """;
}
